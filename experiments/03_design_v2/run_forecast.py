"""Design-v2 experiment 3 — the forecasting arm.

The supervisor asked whether the comparison is "in terms of model fit or forecasting".
Phase 2 scored fit only. This scores the *same* 2x2 grid (classical vs robust x
univariate vs multivariate) on out-of-sample forecasts, so fit and forecast are directly
comparable inside one design.

Protocol: rolling origin, horizons h = 1..12, refit at every origin on the *contaminated*
history, errors measured against the *clean* signal — a method must not be rewarded for
predicting an outlier. RMSE and MAE, pooled over origins and series.

Robust forecasting is not a separate algorithm here: the recurrent forecast reads its
linear recurrence off whatever subspace the backend produced, so a robust backend gives
a robust LRR applied to a robust reconstruction, which is the Rodrigues et al. (2020)
recipe. Only the backend changes between cells.

Usage:  python run_forecast.py
"""

from __future__ import annotations

import json
import sys
import time
from collections import defaultdict
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parent))

from _common import MODES, clean_ranks, make_backends  # noqa: E402

sys.path.insert(0, str(Path(__file__).resolve().parents[2] / "src"))
from rmssa.datasets import make_panel  # noqa: E402
from rmssa.forecasting import rolling_origin_forecast  # noqa: E402

HERE = Path(__file__).resolve().parent
REPORT = Path(__file__).resolve().parents[2] / "report" / "results_v2_forecast.md"

# base -> (T, L, bank_method, bank_names, fixed_rank); mirrors experiment 1
CONFIGS = {
    "synthetic": (300, 60, "surrogate", None, None),
    "airpassengers": (144, 48, "segment", ["airpassengers", "co2", "sunspots"], 8),
}
DEPENDENCE = ("independent", "shared")
EPSILONS = (0.0, 0.05, 0.10)
SEEDS = range(3)
METHODS = ("classical", "RHSSA_huber", "RLSSA_l1")
P, K = 4, 2
H_MAX, N_ORIGINS = 12, 4
REPORT_HORIZONS = (1, 3, 6, 12)


def run() -> list[dict]:
    backends = make_backends()
    rows = []
    for base, (T, L, bank, names, fixed_rank) in CONFIGS.items():
        for dep in DEPENDENCE:
            probe = make_panel(T=T, p=P, k=K, base=base, bank_method=bank,
                               bank_names=names, dependence=dep, contamination=0.0, seed=0)
            if fixed_rank is None:
                r_uni, r_multi = clean_ranks(probe.signal, L)
            else:
                r_uni = r_multi = fixed_rank

            for eps in EPSILONS:
                for seed in SEEDS:
                    pan = make_panel(T=T, p=P, k=K, base=base, bank_method=bank,
                                     bank_names=names, dependence=dep, contamination=eps,
                                     kind="additive", magnitude=8.0, seed=seed)
                    for method in METHODS:
                        for mode in MODES:
                            r = r_uni if mode == "univariate" else r_multi
                            res = rolling_origin_forecast(
                                pan.X, pan.signal, backends[method],
                                window=L, rank=r, mode=mode,
                                h_max=H_MAX, n_origins=N_ORIGINS,
                            )
                            rows.append({
                                "base": base, "dependence": dep, "eps": eps,
                                "method": method, "mode": mode, "rank": r, "seed": seed,
                                "rmse_all": res.rmse(), "mae_all": res.mae(),
                                **{f"rmse_h{h}": res.rmse(h) for h in REPORT_HORIZONS},
                                "n_failed": res.n_failed,
                                "n_origins": res.n_origins,
                            })
    return rows


def aggregate(rows):
    acc = defaultdict(list)
    for r in rows:
        acc[(r["base"], r["dependence"], r["eps"], r["method"], r["mode"])].append(r)
    out = {}
    for k, v in acc.items():
        # nanmean: a cell whose every origin was rejected has no RMSE to average
        out[k] = {
            "rmse_all": float(np.nanmean([x["rmse_all"] for x in v])),
            "mae_all": float(np.nanmean([x["mae_all"] for x in v])),
            "n_failed": int(sum(x["n_failed"] for x in v)),
            "n_origins": int(sum(x["n_origins"] for x in v)),
            "failure_rate": float(sum(x["n_failed"] for x in v)
                                  / max(1, sum(x["n_origins"] for x in v))),
            **{f"rmse_h{h}": float(np.nanmean([x[f"rmse_h{h}"] for x in v]))
               for h in REPORT_HORIZONS},
        }
    return out


def write_report(rows, agg, elapsed):
    lines = [
        "# Design v2 — experiment 3: forecasting arm",
        "",
        f"_Generated by `experiments/03_design_v2/run_forecast.py` in {elapsed:.0f}s; "
        f"{len(rows)} rolling-origin runs, {len(SEEDS)} seeds per cell._",
        "",
        "## Protocol",
        "",
        f"Rolling origin, {N_ORIGINS} origins, horizons h = 1…{H_MAX}, refit at every "
        "origin on the **contaminated** history, scored against the **clean** signal "
        "(so predicting an outlier earns no credit). Recurrent (M)SSA forecast: the LRR "
        "is read off the fitted subspace, so the robust cells forecast with a robust LRR "
        "applied to a robust reconstruction.",
        "",
        "Panels: p=4 series, k=2 common factors, additive outliers at 8× sd.",
        "",
        "## Forecast RMSE, pooled over horizons and series (mean over seeds)",
        "",
        "| base | dependence | eps | classical·uni | classical·multi | Huber·uni | "
        "Huber·multi | L1·uni | L1·multi |",
        "|------|-----------|-----|---------------|-----------------|-----------|"
        "-------------|--------|----------|",
    ]
    for base in CONFIGS:
        for dep in DEPENDENCE:
            for eps in EPSILONS:
                cells = [agg[(base, dep, eps, m, mode)]["rmse_all"]
                         for m in METHODS for mode in MODES]
                lines.append(f"| {base} | {dep} | {eps:.0%} | "
                             + " | ".join(f"{c:.4f}" for c in cells) + " |")

    lines += [
        "",
        "## Robust vs classical forecast gain (multivariate)",
        "",
        "`unstable` is the share of origins whose linear recurrence was explosive and "
        "was therefore refused rather than averaged in — see the note below.",
        "",
        "| base | dependence | eps | classical RMSE | Huber RMSE | gain (×) | "
        "unstable (classical) | unstable (Huber) |",
        "|------|-----------|-----|----------------|------------|----------|"
        "----------------------|------------------|",
    ]
    for base in CONFIGS:
        for dep in DEPENDENCE:
            for eps in EPSILONS:
                ac = agg[(base, dep, eps, "classical", "multivariate")]
                ah = agg[(base, dep, eps, "RHSSA_huber", "multivariate")]
                c, h = ac["rmse_all"], ah["rmse_all"]
                lines.append(f"| {base} | {dep} | {eps:.0%} | {c:.4f} | {h:.4f} | "
                             f"**{c / h if h > 0 else float('inf'):.2f}** | "
                             f"{ac['failure_rate']:.0%} | {ah['failure_rate']:.0%} |")

    lines += ["", "## RMSE by horizon (multivariate cells)", ""]
    header = "| base | dependence | eps | method | " + " | ".join(
        f"h={h}" for h in REPORT_HORIZONS) + " |"
    lines += [header, "|" + "---|" * (4 + len(REPORT_HORIZONS))]
    for base in CONFIGS:
        for dep in DEPENDENCE:
            for eps in EPSILONS:
                for m in METHODS:
                    a = agg[(base, dep, eps, m, "multivariate")]
                    lines.append(f"| {base} | {dep} | {eps:.0%} | {m} | "
                                 + " | ".join(f"{a[f'rmse_h{h}']:.4f}" for h in REPORT_HORIZONS)
                                 + " |")

    failed = sum(v["n_failed"] for v in agg.values())
    total = sum(v["n_origins"] for v in agg.values())
    lines += [
        "",
        "## Note on the stability guard",
        "",
        f"{failed} of {total} origins ({failed / max(1, total):.1%}) produced an "
        "**explosive** linear recurrence and were refused rather than scored.",
        "",
        "This is not a nuisance — it is a finding. A near-vertical estimated subspace "
        "makes the `1/(1 − ν²)` factor in the LRR enormous. On the shortest training "
        "window a robust fit on AirPassengers landed at ν² = 0.9971, giving a dominant "
        "characteristic root of 1.337 and a 12-step forecast ~140× the series' own "
        "scale; other seeds diverged to ~10⁸. Averaged in naively, a single such origin "
        "sets the cell's RMSE and hides every real effect in the table. Origins are "
        "therefore rejected when the dominant root implies growth beyond 10× over the "
        "horizon — a threshold that still permits genuine growth, since a trending "
        "series legitimately has a root just above 1.",
        "",
    ]
    REPORT.write_text("\n".join(lines), encoding="utf-8")


def main() -> int:
    t0 = time.time()
    rows = run()
    elapsed = time.time() - t0
    agg = aggregate(rows)
    write_report(rows, agg, elapsed)
    (HERE / "forecast_raw.json").write_text(json.dumps(rows, indent=1), encoding="utf-8")

    print(f"{len(rows)} rolling runs in {elapsed:.0f}s -> {REPORT}\n")
    print(f"{'base':14s} {'dep':12s} {'eps':>5s} {'classical':>10s} {'Huber':>8s} "
          f"{'gain':>6s} {'unstbl_c':>9s} {'unstbl_h':>9s}")
    for base in CONFIGS:
        for dep in DEPENDENCE:
            for eps in EPSILONS:
                ac = agg[(base, dep, eps, "classical", "multivariate")]
                ah = agg[(base, dep, eps, "RHSSA_huber", "multivariate")]
                print(f"{base:14s} {dep:12s} {eps:5.0%} {ac['rmse_all']:10.4f} "
                      f"{ah['rmse_all']:8.4f} {ac['rmse_all'] / ah['rmse_all']:6.2f} "
                      f"{ac['failure_rate']:9.0%} {ah['failure_rate']:9.0%}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
