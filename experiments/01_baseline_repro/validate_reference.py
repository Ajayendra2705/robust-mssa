"""Day-9 reference validation: confirm our standard SSA against independent ground truth.

Two independent checks, written to report/validation_reference.md:

  A. Analytic SSA-rank ground truth (no external dependency). A series built from
     polynomials x exponentials x sinusoids has a known finite SSA-rank; we verify the
     numerical rank of the trajectory matrix matches theory.

  B. Cross-implementation check vs pyts (skipped with a clear note if pyts is missing):
     full reconstruction identity and leading-component agreement.

Run:  python experiments/01_baseline_repro/validate_reference.py
"""

from __future__ import annotations

from pathlib import Path

import numpy as np

from rmssa.embedding import trajectory_matrix
from rmssa.decomposition import StandardSVD
from rmssa.grouping import elementary_series


def numerical_rank(f, L, rel=1e-9):
    s = np.linalg.svd(trajectory_matrix(f, L), compute_uv=False)
    return int(np.sum(s > rel * s[0]))


ANALYTIC_CASES = [
    ("exponential 0.95^t", lambda t: 0.95 ** t, 1),
    ("constant", lambda t: np.full_like(t, 3.0, dtype=float), 1),
    ("linear trend", lambda t: 0.5 + 0.03 * t, 2),
    ("sinusoid period 17", lambda t: np.sin(2 * np.pi * t / 17), 2),
    ("two exponentials", lambda t: 0.9 ** t + 1.05 ** t, 2),
    ("modulated cosine", lambda t: 0.97 ** t * np.cos(2 * np.pi * t / 23), 2),
    ("two sinusoids", lambda t: np.sin(2 * np.pi * t / 13) + np.sin(2 * np.pi * t / 41), 4),
]


def run_analytic(lines: list[str]) -> bool:
    lines.append("## A. Analytic SSA-rank ground truth\n")
    lines.append("| series | L | expected rank | observed rank | pass |")
    lines.append("|--------|---|---------------|---------------|------|")
    t = np.arange(400)
    ok = True
    for name, builder, expected in ANALYTIC_CASES:
        f = builder(t).astype(float)
        obs = numerical_rank(f, L=120)
        passed = obs == expected
        ok &= passed
        lines.append(f"| {name} | 120 | {expected} | {obs} | {'OK' if passed else 'FAIL'} |")
    lines.append("")
    return ok


def run_pyts(lines: list[str]) -> bool:
    lines.append("## B. Cross-implementation check vs pyts\n")
    try:
        from pyts.decomposition import SingularSpectrumAnalysis
    except Exception as exc:  # not installed
        lines.append(f"_Skipped: pyts unavailable ({exc!r})._\n")
        return True

    rng = np.random.default_rng(0)
    t = np.arange(150)
    f = 0.01 * t + np.sin(2 * np.pi * t / 25) + 0.05 * rng.standard_normal(150)
    L = 40

    ssa = SingularSpectrumAnalysis(window_size=L, groups=L)
    pyts_comp = ssa.fit_transform(f.reshape(1, -1))[0]
    d = StandardSVD().decompose(trajectory_matrix(f, L))
    ours = elementary_series(d, n_components=pyts_comp.shape[0])

    recon_err = float(np.linalg.norm(pyts_comp.sum(0) - f) / np.linalg.norm(f))
    ours_err = float(np.linalg.norm(ours.sum(0) - f) / np.linalg.norm(f))
    lead_corr = float(abs(np.corrcoef(ours[0], pyts_comp[0])[0, 1]))

    ok = recon_err < 1e-7 and ours_err < 1e-7 and lead_corr > 0.999
    lines.append(f"- pyts full-reconstruction rel. error: `{recon_err:.2e}`")
    lines.append(f"- ours full-reconstruction rel. error: `{ours_err:.2e}`")
    lines.append(f"- leading-component |correlation| (ours vs pyts): `{lead_corr:.6f}`")
    lines.append(f"- result: **{'OK' if ok else 'FAIL'}**\n")
    return ok


def main() -> None:
    lines = ["# Reference validation report (Day 9)\n",
             "Generated by `experiments/01_baseline_repro/validate_reference.py`.\n"]
    a_ok = run_analytic(lines)
    b_ok = run_pyts(lines)
    overall = a_ok and b_ok
    lines.insert(2, f"**Overall: {'ALL CHECKS PASSED' if overall else 'FAILURES PRESENT'}**\n")

    out = Path("report/validation_reference.md")
    out.write_text("\n".join(lines))
    print("\n".join(lines))
    print(f"\n[done] wrote {out}")
    if not overall:
        raise SystemExit(1)


if __name__ == "__main__":
    main()
